// TEST_STRATEGY.md
// ============================================================
{
  const unitCases = facts.tests.reduce((s, t) => s + t.cases, 0);
  const e2eChecks = facts.e2e.reduce((s, t) => s + t.checks, 0);
  const integration = facts.tests.filter((t) => t.integration);

  let out = HEADER(
    'Test strategy',
    'What is tested, at which level, and why that level.',
  );

  out += `
## The three levels, and what each is for

**Pure unit tests** cover the arithmetic and the rules: FEFO ordering, expiry
bucketing, GS1 parsing, unit conversion, replenishment, the serial lifecycle
state machine, the scheduled-report window. These have no database because they
have no state — they are functions, and a function is easiest to trust when it
is tested as one.

**Integration tests** run against a real PostgreSQL. Anything that depends on a
transaction, a lock, or a constraint is tested here, because an in-memory
double proves nothing about \`SELECT ... FOR UPDATE\`. The ledger and the
accounting entries are the two that matter most: both are places where a
concurrency bug would corrupt data silently rather than throw.

**End-to-end suites** drive the running API over HTTP as real users, with real
tokens and real permissions. They are the only level that can catch a route
wired to the wrong path, a permission nobody holds, or a guard that lets a
cashier read the controlled register.

**Browser verification** drives the real web application in Chromium against the
real API. It is not a screenshot gallery: the pass or fail comes from
assertions — a page that scrolls sideways, text below the contrast floor, a
control with no accessible name, a request that failed, an exception on the
console. Screenshots are written so a person can look, not so a test can pass.

## What is never done

A test is not weakened to make an implementation pass, and a failing test is
never deleted because it revealed a bug. When a test and the code disagree, one
of them is wrong and the disagreement is the finding.

## Unit and integration suites

${facts.tests.length} suites, ${unitCases} cases. ${integration.length} of them require a database.

| Suite | Cases | Needs a database | Covers |
| --- | --- | --- | --- |
`;
  for (const t of facts.tests.sort((a, b) => a.file.localeCompare(b.file))) {
    out += `| \`${t.file}\` | ${t.cases} | ${t.integration ? 'yes' : 'no'} | ${t.suites.join('; ').replace(/\|/g, '\\|')} |\n`;
  }

  out += `\n## End-to-end suites\n\n${facts.e2e.length} suites, ${e2eChecks} checks, run against a seeded API on port 4000.\n\n`;
  out += '| Suite | Checks |\n| --- | --- |\n';
  for (const t of facts.e2e.sort((a, b) => a.file.localeCompare(b.file))) {
    out += `| \`scripts/${t.file}\` | ${t.checks} |\n`;
  }

  out += `
## Browser verification

\`scripts/ui-verify/verify.mjs\` (\`pnpm test:ui\`) drives ${facts.pages.length} pages.

The matrix is split by what each assertion actually depends on rather than run
as a full cross product. Contrast and accessible naming depend on the theme and
not on the width; overflow depends on the width and not on the theme. Running
all six widths in both themes repeated every finding twelve times, took long
enough to be skipped, and exhausted memory before finishing.

- Content checks: every page, both themes, at 1280px.
- Layout checks: every page, at 375, 428, 768, 1280, 1536 and 1920px.
- Keyboard: the skip link is the first tab stop, 25 consecutive tab stops all
  show a focus indicator, Ctrl+K opens the command palette and Escape closes it.

## Running everything

    pnpm test                  # unit and integration
    pnpm test:e2e*             # the seven end-to-end suites
    pnpm test:ui               # browser verification

The end-to-end suites share a login throttle. Running them back to back trips
it, which is the throttle working; leave about a minute between suites.
`;

  await writeFile(path.join(SPECS, 'TEST_STRATEGY.md'), out);
  console.log('TEST_STRATEGY.md');
}

