// MIGRATION_PLAN.md (the history is generated; the policy is prose)
// ============================================================
{
  const m = facts.migrations;
  let out = HEADER(
    'Migration plan',
    'How the schema moves forward without losing anything a pharmacy needs to keep.',
  );

  out += `
## The rule

Every schema change ships as a migration, applied with \`prisma migrate deploy\`.
Nothing is ever applied with \`db push\` outside a throwaway database, because
push resolves a difference by whatever route is convenient — including dropping
a column — and offers no record of what it did.

Migrations are generated non-interactively, because \`migrate dev\` needs a TTY
that a deployment pipeline does not have:

    npx prisma migrate diff \\
      --from-schema-datasource prisma/schema.prisma \\
      --to-schema-datamodel  prisma/schema.prisma \\
      --script > prisma/migrations/<timestamp>_<name>/migration.sql

## Adding a column to a populated table

A \`NOT NULL\` column with no default fails the moment the table has a row in it.
The order is always:

1. Add the column nullable, or with a default.
2. Backfill it.
3. Verify the backfill — count the rows that are still null.
4. Only then add the constraint.

This project has been bitten by exactly that once, on
\`warehouse_locations.updatedAt\`, which is why the check below runs over every
migration rather than living in somebody's memory.

## What is never done

- No migration drops a column holding data that has not been copied elsewhere.
- No migration resets users, passwords or sessions.
- No deployment reseeds a database that already holds real records: the seed
  refuses to run against a populated database.
- Permissions are the one thing that is *added* automatically on boot
  (\`PermissionSyncService\`), because a release that adds a resource would
  otherwise ship a feature nobody holds the permission to reach. It only ever
  adds. Nothing is revoked, so an administrator who narrowed a role, or a
  custom role somebody built, is left exactly as they left it.

## Applied migrations

${m.length} migrations, in order.

| # | Migration | Statements | Notes |
| --- | --- | --- | --- |
`;
  m.forEach((x, i) => {
    const notes = [
      x.destructive ? '**drops or renames — read before deploying**' : '',
      x.addsNotNullWithoutDefault ? '**adds NOT NULL with no default**' : '',
    ].filter(Boolean).join('; ') || 'additive';
    out += `| ${i + 1} | \`${x.label}\` | ${x.statements} | ${notes} |\n`;
  });

  const risky = m.filter((x) => x.destructive || x.addsNotNullWithoutDefault);
  out += `\n${risky.length === 0
    ? 'No migration in the history drops a column, renames a table, or adds a\n' +
      '`NOT NULL` column without a default. Every one is additive and can be applied\n' +
      'to a populated database without a backfill step.'
    : `${risky.length} migration(s) need reading before a deployment: ` +
      risky.map((x) => `\`${x.label}\``).join(', ') + '.'}\n`;

  await writeFile(path.join(SPECS, 'MIGRATION_PLAN.md'), out);
  console.log(`MIGRATION_PLAN.md (${risky.length} risky)`);
}

