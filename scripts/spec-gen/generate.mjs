// Write the specification documents that are derived from code, so they cannot
// drift from it. Anything that is a judgement rather than a fact — why the
// architecture is shaped this way, what the security posture is — is written by
// hand and lives in its own file; this only generates what the code can prove.
//
//   node scripts/spec-gen/extract.mjs && node scripts/spec-gen/generate.mjs
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const facts = JSON.parse(await readFile(path.join(ROOT, 'scripts/spec-gen/facts.json'), 'utf8'));
const SPECS = path.join(ROOT, 'specs');

const HEADER = (title, note) => `<!--
  GENERATED by scripts/spec-gen/generate.mjs from the code itself.
  Do not edit by hand: run \`node scripts/spec-gen/extract.mjs && node scripts/spec-gen/generate.mjs\`.
-->

# ${title}

${note}

Generated ${new Date().toISOString().slice(0, 10)} from the schema, the route table and the permission catalogue.
`;

// ============================================================
// DATA_MODEL.md
// ============================================================
{
  const { models, enums } = facts.dataModel;

  // Group by the part of the system a model belongs to, so a reader looking for
  // "how is a batch stored" is not scrolling through 114 alphabetical models.
  const GROUPS = [
    ['Identity and access', /^(User|Role|Permission|UserRole|RolePermission|UserScope|Session|ApiKey|PasswordReset)/],
    ['Organisation', /^(Company|BusinessUnit|Region|Branch|Department|Warehouse|WarehouseLocation)/],
    ['Drug master', /^(Product|Category|Manufacturer|Ingredient|Unit|Barcode|ProductCategory|ProductBarcode|ProductUnit|ProductIngredient|ProductRelation|ProductAttribute)/],
    ['Stock', /^(Batch|Serial|Inventory|Stock|Reservation|CostLayer|CostConsumption)/],
    ['Procurement', /^(Supplier|Purchase|Rfq|Quotation|GoodsReceipt)/],
    ['Sales and dispensing', /^(Sale|Payment|CashSession|Prescription|Dispensing|Patient|Customer|LoyaltyLedger)/],
    ['Quality and compliance', /^(Quality|Recall|Return|Disposal|Damage|Quarantine|Temperature|Sensor|ControlledRegister)/],
    ['Finance', /^(Account|Journal|SupplierInvoice|FinanceNote|Valuation|Tax)/],
    ['Platform', /^(Setting|FeatureFlag|AuditLog|Notification|Automation|Workflow|Job|Import|Document|Integration|Webhook|SavedReport|Backup|Translation)/],
  ];

  const grouped = new Map(GROUPS.map(([name]) => [name, []]));
  grouped.set('Other', []);
  for (const m of models) {
    const hit = GROUPS.find(([, re]) => re.test(m.name));
    grouped.get(hit ? hit[0] : 'Other').push(m);
  }

  let out = HEADER(
    'Data model',
    'Every table, what it is for, and the fields that carry meaning rather than plumbing.\n\n' +
    'Money and quantities are `Decimal`, never float: a pharmacy that rounds a\n' +
    'unit price in binary floating point will disagree with its own invoices.\n' +
    'Primary keys are UUIDs so a record can be created in one branch and\n' +
    'referenced in another without a central sequence.',
  );

  out += `\n**${models.length} tables, ${enums.length} enumerations.**\n`;

  for (const [group, list] of grouped) {
    if (!list.length) continue;
    out += `\n## ${group}\n\n`;
    for (const m of list.sort((a, b) => a.name.localeCompare(b.name))) {
      out += `### ${m.name}${m.table ? ` — \`${m.table}\`` : ''}\n\n`;
      if (m.doc) out += `${m.doc}\n\n`;
      const meaningful = m.fields.filter(
        (f) => !['id', 'createdAt', 'updatedAt'].includes(f.name) && !f.relation,
      );
      if (meaningful.length) {
        out += '| Field | Type | Notes |\n| --- | --- | --- |\n';
        for (const f of meaningful) {
          const notes = [
            f.doc,
            /@unique/.test(f.attributes) ? 'unique' : '',
            /@default/.test(f.attributes) ? `default ${/@default\(([^)]*)\)/.exec(f.attributes)?.[1]}` : '',
          ].filter(Boolean).join('; ');
          out += `| \`${f.name}\` | ${f.type} | ${notes.replace(/\|/g, '\\|')} |\n`;
        }
      }
      const rels = m.fields.filter((f) => f.relation);
      if (rels.length) {
        out += `\nRelations: ${rels.map((r) => `\`${r.name}\` → ${r.type.replace(/[?[\]]/g, '')}`).join(', ')}\n`;
      }
      if (m.indexes.length) {
        out += `\nIndexes and constraints: ${m.indexes.map((i) => `\`${i}\``).join(', ')}\n`;
      }
      out += '\n';
    }
  }

  out += '\n## Enumerations\n\n';
  for (const e of enums.sort((a, b) => a.name.localeCompare(b.name))) {
    out += `- **${e.name}**: ${e.values.map((v) => `\`${v}\``).join(', ')}\n`;
  }

  await writeFile(path.join(SPECS, 'DATA_MODEL.md'), out);
  console.log('DATA_MODEL.md');
}

// ============================================================
// API_CONTRACTS.md
// ============================================================
{
  const byTag = new Map();
  for (const h of facts.handlers) {
    const key = h.tag ?? h.module;
    if (!byTag.has(key)) byTag.set(key, []);
    const full = ('/' + [h.controllerPath, h.routePath].filter(Boolean).join('/')).replace(/\/+/g, '/');
    byTag.get(key).push({ ...h, full });
  }

  const unguarded = facts.handlers.filter((h) => !h.permissions.length && !h.isPublic);

  let out = HEADER(
    'API contracts',
    'Every route the application serves, the permissions it requires, and what it is for.\n\n' +
    'Authorization is declared on the handler and enforced by a guard before the\n' +
    'handler runs. A route with no `@RequirePermissions` and no `@Public` is a\n' +
    'route nobody decided about, so they are listed separately below rather than\n' +
    'buried in the table.',
  );

  out += `\n**${facts.routes.length} routes across ${byTag.size} areas.**\n\n`;
  out += 'Every route is served twice: unversioned under `/api`, and under `/api/v1`.\n';
  out += 'A client that has been calling `/api/...` keeps working; a new integration\n';
  out += 'can pin `/api/v1/...`. A future `v2` is added per controller with\n';
  out += '`@Version(\'2\')`, and `v1` stays as it is until it is deliberately retired.\n';

  for (const [tag, list] of [...byTag.entries()].sort()) {
    out += `\n## ${tag}\n\n`;
    out += '| Method | Path | Requires | Purpose |\n| --- | --- | --- | --- |\n';
    for (const h of list.sort((a, b) => a.full.localeCompare(b.full))) {
      const guard = h.isPublic
        ? '_public_'
        : h.permissions.length
          ? h.permissions.map((p) => `\`${p}\``).join(' + ')
          : '**authenticated only**';
      out += `| ${h.method} | \`${h.full}\` | ${guard} | ${(h.summary ?? '').replace(/\|/g, '\\|')} |\n`;
    }
  }

  out += '\n## Routes with no declared permission\n\n';
  if (!unguarded.length) {
    out += 'None. Every route either declares the permissions it needs or is explicitly public.\n';
  } else {
    out += `${unguarded.length} route(s) require authentication but declare no permission. Each is\n`;
    out += 'listed so the choice is visible rather than accidental:\n\n';
    for (const h of unguarded) {
      const full = ('/' + [h.controllerPath, h.routePath].filter(Boolean).join('/')).replace(/\/+/g, '/');
      out += `- \`${h.method} ${full}\` (${h.module})\n`;
    }
  }

  await writeFile(path.join(SPECS, 'API_CONTRACTS.md'), out);
  console.log(`API_CONTRACTS.md (${unguarded.length} unguarded)`);
}

// ============================================================
// PERMISSION_MATRIX.md
// ============================================================
{
  const { catalogue, codes, roles } = facts.permissions;

  let out = HEADER(
    'Permission matrix',
    'Who may do what. A permission code is `module.resource.ACTION`, and every\n' +
    'decision is taken on the server: the client uses this catalogue only to decide\n' +
    'what to render, never whether to allow.',
  );

  out += `\n**${codes.length} permissions across ${catalogue.length} resources, granted through ${roles.length} roles.**\n`;

  out += '\n## Resources\n\n| Module | Resource | Label | Actions |\n| --- | --- | --- | --- |\n';
  for (const r of catalogue) {
    out += `| ${r.module} | ${r.resource} | ${r.label} | ${r.actions.join(', ')} |\n`;
  }

  out += '\n## Roles\n\n';
  for (const r of roles) {
    out += `### ${r.name} (\`${r.code}\`)\n\n${r.description}\n\n`;
    out += `Holds ${r.permissions.length} of ${codes.length} permissions.\n\n`;
    const byModule = new Map();
    for (const code of r.permissions) {
      const [mod] = code.split('.');
      if (!byModule.has(mod)) byModule.set(mod, []);
      byModule.get(mod).push(code.split('.').slice(1).join('.'));
    }
    for (const [mod, list] of [...byModule.entries()].sort()) {
      out += `- **${mod}**: ${list.sort().join(', ')}\n`;
    }
    out += '\n';
  }

  out += '## Coverage\n\n';
  out += 'Every permission and the roles that hold it. A permission held by nobody is\n';
  out += 'a feature nobody can reach, so the empty rows matter more than the full ones.\n\n';
  out += '| Permission | Held by |\n| --- | --- |\n';
  for (const code of codes) {
    const holders = roles.filter((r) => r.permissions.includes(code)).map((r) => r.code);
    out += `| \`${code}\` | ${holders.length ? holders.join(', ') : '**nobody**'} |\n`;
  }

  await writeFile(path.join(SPECS, 'PERMISSION_MATRIX.md'), out);
  console.log('PERMISSION_MATRIX.md');
}

